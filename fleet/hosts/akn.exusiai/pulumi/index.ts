import { SopsFile } from "@chezmoi.sh/pulumi-sops-file";
import * as b2 from "@pulumi/b2";
import * as pulumi from "@pulumi/pulumi";

import { backupsBucketName, backupsKeyId, backupsKeySecret } from "./stack/backblaze";
// Imported for their side effects only (resources are created on load).
import "./stack/dns";
import { minecraftOidcClientId, minecraftOidcClientSecret } from "./stack/pocket-id";
import { tailscaleAuthKey } from "./stack/tailscale";

// Only what is read from outside is exported: the instance IP and the bucket name.
export { backupsBucketName } from "./stack/backblaze";
export { publicIp } from "./stack/oci";

// S3 endpoint of the Backblaze account, as reported by the provider (https://s3.<region>.backblazeb2.com).
const b2Account = b2.getAccountInfoOutput();

// -----------------------------------------------------------------------------
// NixOS secrets generated by this stack
// -----------------------------------------------------------------------------
// Rewritten at every `pulumi up` (see ptilopsis for the same pattern). The values nothing
// generates (restic password, Wings node) stay in nix/secrets/manual.sops.yaml.
// The creation rules, recipients included, live in nix/.sops.yaml.
new SopsFile("exusiai-sops", {
	file: "../nix/secrets/exusiai.sops.json",
	config: "../nix/.sops.yaml",
	content: pulumi.output({
		tailscale_authkey: tailscaleAuthKey,
		restic_repository: pulumi.interpolate`s3:${b2Account.s3ApiUrl}/${backupsBucketName}/restic`,
		restic_b2_env: pulumi.interpolate`AWS_ACCESS_KEY_ID=${backupsKeyId}\nAWS_SECRET_ACCESS_KEY=${backupsKeySecret}\n`,
		oauth_pocketid_client_id: minecraftOidcClientId,
		oauth_pocketid_client_secret: minecraftOidcClientSecret,
	}),
});
